import "C"

import (
	"context"
	"fmt"
	"sync"
	"time"
	"unsafe"
)

// DarwinBoard uses NSPasteboard directly so it can watch changeCount (a cheap
// counter, no content transfer) and skip password-manager copies.
type DarwinBoard struct {
	mu sync.Mutex
}

// How often changeCount is checked. Reading the counter costs no content
// transfer, so this can be much tighter than the polling sync interval.
const darwinWatchInterval = 200 * time.Millisecond

func NewBoard() (Board, error) {
	return &DarwinBoard{}, nil
}

func takeBytes(p unsafe.Pointer, n C.int) []byte {
	if p == nil {
		return nil
	}
	defer C.free(p)
	return C.GoBytes(p, n)
}

func (b *DarwinBoard) ReadText() ([]byte, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	var n C.int
	data := takeBytes(C.cs_read_text(&n), n)
	if len(data) == 0 {
		return nil, fmt.Errorf("clipboard: no text content")
	}
	return data, nil
}

func (b *DarwinBoard) ReadImage() ([]byte, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	var n C.int
	data := takeBytes(C.cs_read_png(&n), n)
	if len(data) == 0 {
		return nil, fmt.Errorf("clipboard: no image content")
	}
	return data, nil
}

func (b *DarwinBoard) WriteText(data []byte) error {
	if len(data) == 0 {
		return fmt.Errorf("clipboard: empty text")
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if C.cs_write_text(unsafe.Pointer(&data[0]), C.int(len(data))) == 0 {
		return fmt.Errorf("clipboard: text write failed (invalid UTF-8?)")
	}
	return nil
}

func (b *DarwinBoard) WriteImage(data []byte) error {
	if len(data) == 0 {
		return fmt.Errorf("clipboard: empty image")
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if C.cs_write_png(unsafe.Pointer(&data[0]), C.int(len(data))) == 0 {
		return fmt.Errorf("clipboard: image write failed")
	}
	return nil
}

func (b *DarwinBoard) Sensitive() bool {
	return C.cs_sensitive() != 0
}

// Watch signals once at startup and then whenever changeCount moves.
func (b *DarwinBoard) Watch(ctx context.Context) <-chan struct{} {
	ch := make(chan struct{}, 1)
	go func() {
		defer close(ch)
		last := C.cs_change_count()
		ch <- struct{}{}
		ticker := time.NewTicker(darwinWatchInterval)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				if n := C.cs_change_count(); n != last {
					last = n
					select {
					case ch <- struct{}{}:
					default:
					}
				}
			}
		}
	}()
	return ch
}
